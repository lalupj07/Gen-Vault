    #[test]
    fn png_produces_jpeg_thumb() {
        let out = generate_jpeg_thumb(TINY_PNG, 256).expect("png thumb");
        assert!(out.starts_with(&[0xFF, 0xD8, 0xFF]), "expected JPEG SOI");
        assert!(out.ends_with(&[0xFF, 0xD9]), "expected JPEG EOI");
    }

    #[test]
    fn jpeg_input_produces_jpeg_thumb() {
        let out = generate_jpeg_thumb(TINY_JPEG, 256).expect("jpeg thumb");
        assert!(out.starts_with(&[0xFF, 0xD8, 0xFF]));
    }

    #[test]
    fn rejects_invalid_bytes() {
        assert_eq!(
            generate_jpeg_thumb(b"not-an-image", 256),
            Err(ThumbError::Decode)
        );
    }

    #[test]
    fn scaled_dimensions_landscape() {
        assert_eq!(scaled_dimensions(512, 256, 256), (256, 128));
    }

    #[test]
    fn scaled_dimensions_portrait() {
        assert_eq!(scaled_dimensions(200, 400, 256), (128, 256));
    }

    #[test]
    fn does_not_upscale_small_image() {
        let out = generate_jpeg_thumb(TINY_PNG, 256).expect("thumb");
        let decoded = ImageReader::new(Cursor::new(&out))
            .with_guessed_format()
            .unwrap()
            .decode()
            .unwrap();
        assert_eq!(decoded.dimensions(), (1, 1));
    }

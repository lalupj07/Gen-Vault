//! Resize decoded image bytes into a JPEG thumbnail for encrypted storage.

use image::codecs::jpeg::JpegEncoder;
use image::{GenericImageView, ImageEncoder, ImageReader};
use std::io::Cursor;
use thiserror::Error;

const DEFAULT_JPEG_QUALITY: u8 = 75;

#[derive(Error, Debug, PartialEq, Eq)]
pub enum ThumbError {
    #[error("Failed to decode image")]
    Decode,
    #[error("Failed to encode JPEG thumbnail")]
    Encode,
}

/// Decode `plain`, resize so the longest edge is at most `max_edge` (aspect preserved),
/// and return JPEG bytes at quality ~75.
pub fn generate_jpeg_thumb(plain: &[u8], max_edge: u32) -> Result<Vec<u8>, ThumbError> {
    if max_edge == 0 {
        return Err(ThumbError::Encode);
    }

    let img = ImageReader::new(Cursor::new(plain))
        .with_guessed_format()
        .map_err(|_| ThumbError::Decode)?
        .decode()
        .map_err(|_| ThumbError::Decode)?;

    let (width, height) = img.dimensions();
    let thumb = if width <= max_edge && height <= max_edge {
        img
    } else {
        let (new_w, new_h) = scaled_dimensions(width, height, max_edge);
        img.resize(new_w, new_h, image::imageops::FilterType::Triangle)
    };

    let rgb = thumb.to_rgb8();
    let mut out = Vec::new();
    JpegEncoder::new_with_quality(&mut out, DEFAULT_JPEG_QUALITY)
        .write_image(
            rgb.as_raw(),
            rgb.width(),
            rgb.height(),
            image::ExtendedColorType::Rgb8,
        )
        .map_err(|_| ThumbError::Encode)?;

    Ok(out)
}

fn scaled_dimensions(width: u32, height: u32, max_edge: u32) -> (u32, u32) {
    if width >= height {
        let new_h = ((height as u64 * max_edge as u64) / width as u64).max(1) as u32;
        (max_edge, new_h)
    } else {
        let new_w = ((width as u64 * max_edge as u64) / height as u64).max(1) as u32;
        (new_w, max_edge)
    }
}

